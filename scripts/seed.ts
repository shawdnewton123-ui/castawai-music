/**
 * Seed script — creates DEMO content, clearly labeled as demo.
 * Run: npm run db:seed
 *
 * Demo artwork is generated as SVG files; demo audio is arranged per title and
 * genre by scripts/gen-music.py (drums, bass, chords, lead — no vocals, not
 * licensed music). Users created: one admin, one artist, plus their published
 * demo releases.
 */
import "dotenv/config";
import { execSync } from "node:child_process";
import { randomBytes, scryptSync } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { Pool } from "pg";
import { drizzle } from "drizzle-orm/node-postgres";
import { eq } from "drizzle-orm";
import { artists, releases, tracks, users } from "../src/db/schema";
import { slugify } from "../src/lib/catalog";

const pool = new Pool({ connectionString: process.env.DATABASE_URL });
const db = drizzle(pool);

function hashPassword(password: string): string {
  const salt = randomBytes(16).toString("hex");
  const derived = scryptSync(password, salt, 64);
  return `${salt}:${derived.toString("hex")}`;
}

function coverSvg(title: string, artist: string, hue: number, tag: string) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="800">
  <defs>
    <radialGradient id="g" cx="70%" cy="20%" r="90%">
      <stop offset="0%" stop-color="hsl(${hue},80%,58%)"/>
      <stop offset="45%" stop-color="hsl(${hue},70%,26%)"/>
      <stop offset="100%" stop-color="#05070D"/>
    </radialGradient>
  </defs>
  <rect width="800" height="800" fill="url(#g)"/>
  <g stroke="rgba(233,238,248,0.14)" fill="none" stroke-width="1.5">
    ${Array.from({ length: 9 }, (_, i) => `<circle cx="400" cy="400" r="${60 + i * 42}"/>`).join("")}
  </g>
  <circle cx="400" cy="400" r="26" fill="rgba(233,238,248,0.85)"/>
  <text x="56" y="120" font-family="Arial, sans-serif" font-size="26" letter-spacing="10" fill="rgba(233,238,248,0.7)">CASTAWAI</text>
  <text x="56" y="620" font-family="Arial, sans-serif" font-weight="bold" font-size="64" fill="#E8EDF7">${title.replace(/[<>&]/g, "")}</text>
  <text x="56" y="672" font-family="Arial, sans-serif" font-size="30" fill="rgba(220,227,240,0.75)">${artist.replace(/[<>&]/g, "")}</text>
  <text x="56" y="740" font-family="Arial, sans-serif" font-size="20" letter-spacing="4" fill="rgba(141,153,179,0.9)">DEMO · ${tag.toUpperCase()}</text>
</svg>`;
  return Buffer.from(svg).toString("base64");
}

function demoAudio(title: string, genre: string, hue: number, seconds: number): string {
  // Arranged demo song per title/genre, generated by scripts/gen-music.py.
  const out = `demo-audio/demo-${180 + hue}-${seconds}.mp3`;
  execSync(
    `python3 scripts/gen-music.py --title ${JSON.stringify(title)} --genre ${JSON.stringify(genre)} --seconds ${seconds} --out public/${out}`
  );
  return out;
}

type SeedRelease = {
  title: string;
  type: "album" | "ep" | "single";
  creativeMethod: "human" | "ai_assisted" | "ai_generated";
  genre: string;
  description: string;
  tracks: string[];
};

async function upsertUser(email: string, password: string, displayName: string, role: "listener" | "artist" | "admin") {
  const existing = await db.select().from(users).where(eq(users.email, email)).limit(1);
  if (existing[0]) return existing[0];
  const [u] = await db
    .insert(users)
    .values({ email, passwordHash: hashPassword(password), displayName, role })
    .returning();
  return u;
}

async function seedArtist(
  name: string,
  bio: string,
  verified: boolean,
  seed: SeedRelease[],
  hueOffset: number
) {
  const slug = slugify(name);
  const existing = await db.select().from(artists).where(eq(artists.slug, slug)).limit(1);
  if (existing[0]) return existing[0];
  const [artist] = await db.insert(artists).values({ name, slug, bio, verified }).returning();

  let hue = hueOffset;
  for (const rel of seed) {
    const relSlug = slugify(`${name}-${rel.title}`);
    const coverFile = `demo-artwork/${relSlug}.svg`;
    writeFileSync(
      `public/${coverFile}`,
      Buffer.from(coverSvg(rel.title, name, hue, rel.creativeMethod.replace("_", "-")), "base64")
    );
    hue = (hue + 47) % 360;
    const [release] = await db
      .insert(releases)
      .values({
        artistId: artist.id,
        title: rel.title,
        slug: relSlug,
        type: rel.type,
        creativeMethod: rel.creativeMethod,
        genre: rel.genre,
        releaseDate: new Date(Date.now() - Math.floor(Math.random() * 90) * 86400000),
        coverUrl: `/${coverFile}`,
        description: rel.description,
        status: "approved",
        explicit: false,
        ownershipDeclaration: true,
        distributionRights: "Demo release — distribution rights declared for development only.",
        aiToolDisclosures:
          rel.creativeMethod === "human"
            ? null
            : "Demo disclosure: generated for development; production releases collect full tool and rights disclosures.",
      })
      .returning();

    for (let i = 0; i < rel.tracks.length; i++) {
      const audioPath = demoAudio(rel.tracks[i], rel.genre, hue + i * 30, 30);
      await db.insert(tracks).values({
        releaseId: release.id,
        title: rel.tracks[i],
        trackNumber: i + 1,
        durationSec: 30,
        audioPath,
      });
    }
  }
  return artist;
}

